DEFAULT_ICON = "file-text"


def icon_for(text: str) -> str:
    """Имя иконки по названию услуги или раздела; если ничего не подошло — ``file-text``."""
    low = (text or "").lower()
    for needle, name in _KEYWORDS:
        if needle in low:
            return name
    return DEFAULT_ICON


def svg(name: str, size: int = 24) -> str:
    """Готовая разметка ``<svg>`` (декоративная, ``aria-hidden``); неизвестное имя → иконка по умолчанию."""
    paths = ICONS.get(name) or ICONS[DEFAULT_ICON]
    body = "".join(f'<path d="{d}"/>' for d in paths)
    return (
        f'<svg class="ico" width="{int(size)}" height="{int(size)}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" '
        f'aria-hidden="true" focusable="false">{body}</svg>'
    )
